#!/usr/bin/env node
/**
 * circus-sandbox 文档与手写 Rust 规模检查。
 * 不运行 Cargo，不证明构建、运行或隔离。
 *
 * 链接只检查 mdast-util-from-markdown 实际产出的节点：行内链接、图片、自动链接，
 * 以及解析器已识别的引用式链接和定义。未匹配定义的引用语法会留在文本节点里，
 * 本检查不把它当成链接，也不声称能发现这类未定义引用。不访问网络。
 * 标题片段只接受 github-slugger 生成的锚点，不另造别名。
 * Markdown 不把 #L1 这类行号锚点当成标题。目录片段只解析该目录根 README.md，
 * 不扫描目录；缺少 README.md 即失败。手写 Rust 只豁免文件开头的生成注释头。
 */

import { spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const MAX_HANDWRITTEN_RUST_LINES = 1200;
const qaDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(qaDir, "..", "..");
const sandboxRoot = path.join(repoRoot, "circus-sandbox");
const SKIP_WALK = new Set([".git", ".omp", "circus-paseo", "node_modules", "target"]);

const EXTERNAL_SCHEME =
  /^(?:https?|mailto|ftp|ftps|irc|ircs|ws|wss|data|javascript|tel|cid|ssh|git|svn):/i;
const LINE_ANCHOR = /^L(\d+)(?:-L(\d+))?$/i;
const GENERATED_HEADER =
  /@generated\b|DO NOT EDIT|Code generated|autogenerated|auto-generated|This file is generated/i;
const GENERATED_HEADER_LINES = 30;

function display(file) {
  return path.relative(repoRoot, file).split(path.sep).join("/");
}

function byDisplay(a, b) {
  return display(a).localeCompare(display(b), "en");
}

function readError(file, error) {
  const detail = error && error.code ? error.code : error.message;
  return `${display(file)}: 无法读取 (${detail})`;
}

function isSkippedTree(abs) {
  const rel = path.relative(repoRoot, abs);
  if (!insideRepo(abs)) return true;
  return rel.split(path.sep).some((part) => SKIP_WALK.has(part));
}

function walkFiles(dir, onFile, skipNames, errors, seen) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch (error) {
    errors.push(readError(dir, error));
    return;
  }
  for (const entry of entries) {
    if (skipNames.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) {
      let real;
      let stat;
      try {
        real = fs.realpathSync(full);
        stat = fs.statSync(real);
      } catch (error) {
        errors.push(readError(full, error));
        continue;
      }
      if (isSkippedTree(real)) continue;
      if (stat.isDirectory()) {
        if (seen.has(real)) continue;
        seen.add(real);
        walkFiles(real, onFile, skipNames, errors, seen);
      } else if (stat.isFile()) {
        // 扩展名看链接自己的 basename，不能改用目标 payload.txt 的名字。
        onFile(full, entry.name);
      }
      continue;
    }
    if (entry.isDirectory()) walkFiles(full, onFile, skipNames, errors, seen);
    else if (entry.isFile()) onFile(full, entry.name);
  }
}

function walkTree(dir, onFile, skipNames, errors) {
  let real;
  try {
    real = fs.realpathSync(dir);
  } catch (error) {
    errors.push(readError(dir, error));
    return;
  }
  if (!insideRepo(real)) {
    errors.push(`${display(dir)}: 目录超出仓库`);
    return;
  }
  walkFiles(real, onFile, skipNames, errors, new Set([real]));
}

const MANDATORY_DOCS = ["README.md", "AGENTS.md", "circus-sandbox/AGENTS.md"];

function requireDoc(rel, errors) {
  const abs = path.resolve(repoRoot, ...rel.split("/"));
  const found = locateInRepo(abs);
  if (!found) {
    errors.push(`${rel}: 必需文档缺失`);
    return;
  }
  if (found.unreadable) {
    errors.push(readError(abs, found.unreadable));
    return;
  }
  if (found.outside || !found.stat.isFile()) {
    errors.push(`${rel}: 必需文档缺失`);
    return;
  }
  try {
    fs.accessSync(found.path, fs.constants.R_OK);
  } catch (error) {
    errors.push(readError(found.path, error));
    return;
  }
  return found.path;
}

function markdownFiles(errors) {
  const files = new Set();
  for (const rel of MANDATORY_DOCS) {
    const found = requireDoc(rel, errors);
    if (found) files.add(found);
  }
  const securityDoc = ".github/sandbox-security.md";
  if (fs.existsSync(path.resolve(repoRoot, securityDoc))) {
    const found = requireDoc(securityDoc, errors);
    if (found) files.add(found);
  }
  walkTree(sandboxRoot, (full, name) => {
    if (name.endsWith(".md")) files.add(path.resolve(full));
  }, new Set(["node_modules"]), errors);
  return [...files].sort(byDisplay);
}

function linkFiles(docs, errors) {
  const files = new Set(docs);
  const rel = ".github/pull_request_template.md";
  const found = locateInRepo(path.resolve(repoRoot, ".github", "pull_request_template.md"));
  if (!found) return [...files].sort(byDisplay);
  if (found.unreadable) {
    errors.push(readError(path.join(repoRoot, ".github", "pull_request_template.md"), found.unreadable));
  } else if (found.outside || !found.stat.isFile()) {
    errors.push(`${rel}: 链接检查目标不是仓库内文件`);
  } else {
    try {
      fs.accessSync(found.path, fs.constants.R_OK);
      files.add(found.path);
    } catch (error) {
      errors.push(readError(found.path, error));
    }
  }
  return [...files].sort(byDisplay);
}

function runNode(script, args) {
  return new Promise((resolve) => {
    const child = spawn(process.execPath, [script, ...args], {
      cwd: qaDir,
      stdio: "inherit",
      windowsHide: true,
    });
    child.on("error", (error) => {
      console.error(error.message);
      resolve(1);
    });
    child.on("close", (code) => resolve(code ?? 1));
  });
}

function missingTool(script, name) {
  if (fs.existsSync(script)) return false;
  console.error(`${name} 未安装。请在仓库根目录执行 npm --prefix circus-sandbox/qa ci`);
  return true;
}

function formatLintError(file, error) {
  const rule = Array.isArray(error.ruleNames) ? error.ruleNames.join("/") : "markdownlint";
  const line = error.lineNumber ?? 1;
  const column = error.errorRange && error.errorRange[0] ? `:${error.errorRange[0]}` : "";
  const severity = error.severity ? ` ${error.severity}` : "";
  const description = error.ruleDescription ?? "";
  const detail = error.errorDetail ? ` [${error.errorDetail}]` : "";
  const context = error.errorContext ? ` [Context: "${error.errorContext}"]` : "";
  return `${display(file)}:${line}${column}${severity} ${rule} ${description}${detail}${context}`;
}

function reportMarkdownlint(results) {
  if (!results || typeof results !== "object" || Array.isArray(results)) {
    console.error("markdownlint 没有返回结果");
    return 1;
  }
  const rows = [];
  for (const [file, errors] of Object.entries(results)) {
    if (!Array.isArray(errors)) {
      console.error(`${display(file)}: markdownlint 结果无效`);
      return 1;
    }
    for (const error of errors) rows.push({ file, error });
  }
  rows.sort((a, b) => {
    const byFile = display(a.file).localeCompare(display(b.file), "en");
    if (byFile !== 0) return byFile;
    const byLine = (a.error.lineNumber ?? 0) - (b.error.lineNumber ?? 0);
    if (byLine !== 0) return byLine;
    const aCol = (a.error.errorRange && a.error.errorRange[0]) || 0;
    const bCol = (b.error.errorRange && b.error.errorRange[0]) || 0;
    if (aCol !== bCol) return aCol - bCol;
    const aRule = Array.isArray(a.error.ruleNames) ? a.error.ruleNames[0] : "";
    const bRule = Array.isArray(b.error.ruleNames) ? b.error.ruleNames[0] : "";
    return String(aRule).localeCompare(String(bRule), "en");
  });
  for (const row of rows) console.error(formatLintError(row.file, row.error));
  return rows.length === 0 ? 0 : 1;
}

async function loadMarkdownlint() {
  let api;
  try {
    api = await import("markdownlint/promise");
  } catch (error) {
    if (error?.code === "ERR_MODULE_NOT_FOUND") {
      console.error("markdownlint 未安装。请在仓库根目录执行 npm --prefix circus-sandbox/qa ci");
      return null;
    }
    throw error;
  }
  if (typeof api.lint !== "function" || typeof api.readConfig !== "function") {
    console.error("markdownlint 导出不完整");
    return null;
  }
  return api;
}

async function runMarkdownlint(files) {
  // 文件列表已由本脚本枚举。规则在 .markdownlint.json，不再调用 CLI，也不再 glob。
  // MD013 关闭：中文散文和长链接不按 80 列折行。MD033 关闭：允许 HTML 注释。
  // MD036 关闭：列表项整行加粗不是标题。MD024 siblings_only：同名标题只在同一父节冲突。
  // MD051/MD053/MD054 关闭：标题片段由 github-slugger 检查，不强制链接风格。
  let api;
  try {
    api = await loadMarkdownlint();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
  if (!api) return 1;
  const configPath = path.join(qaDir, ".markdownlint.json");
  let config;
  try {
    config = await api.readConfig(configPath);
  } catch (error) {
    console.error(readError(configPath, error));
    return 1;
  }
  if (!config || typeof config !== "object" || Array.isArray(config)) {
    console.error(`${display(configPath)}: markdownlint 配置无效`);
    return 1;
  }
  console.log("markdownlint");
  let results;
  try {
    results = await api.lint({ files, config });
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
  return reportMarkdownlint(results);
}

async function runPrettier(files, write) {
  const script = path.join(qaDir, "node_modules", "prettier", "bin", "prettier.cjs");
  if (missingTool(script, "prettier")) return 1;
  console.log(write ? "prettier --write" : "prettier --check");
  return runNode(script, [
    "--config",
    path.join(qaDir, ".prettierrc.json"),
    write ? "--write" : "--check",
    "--ignore-unknown",
    ...files,
  ]);
}

function countSourceLines(buf) {
  if (buf.length === 0) return 0;
  let lines = 0;
  let lastWasBreak = false;
  for (let i = 0; i < buf.length; i++) {
    const byte = buf[i];
    if (byte === 13 || byte === 10) {
      lines++;
      lastWasBreak = true;
      if (byte === 13 && buf[i + 1] === 10) i++;
    } else {
      lastWasBreak = false;
    }
  }
  if (!lastWasBreak) lines++;
  return lines;
}

function firstSourceLines(buf, maxLines) {
  let breaks = 0;
  for (let i = 0; i < buf.length; i++) {
    if (buf[i] !== 10 && buf[i] !== 13) continue;
    breaks++;
    if (buf[i] === 13 && buf[i + 1] === 10) i++;
    if (breaks === maxLines) return buf.subarray(0, i + 1);
  }
  return buf;
}

function generatedCommentHeader(text) {
  let i = 0;
  if (text.charCodeAt(0) === 0xfeff) i++;
  let line = 1;
  let header = "";
  while (i < text.length && line <= GENERATED_HEADER_LINES) {
    const ch = text[i];
    if (ch === " " || ch === "\t" || ch === "\f" || ch === "\v") {
      i++;
      continue;
    }
    if (ch === "\n") {
      line++;
      i++;
      continue;
    }
    if (ch === "\r") {
      line++;
      i++;
      if (text[i] === "\n") i++;
      continue;
    }
    if (ch === "/" && text[i + 1] === "/") {
      i += 2;
      while (i < text.length && text[i] !== "\n" && text[i] !== "\r") {
        header += text[i];
        i++;
      }
      header += "\n";
      continue;
    }
    if (ch === "/" && text[i + 1] === "*") {
      i += 2;
      let depth = 1;
      while (i < text.length && depth > 0 && line <= GENERATED_HEADER_LINES) {
        if (text[i] === "/" && text[i + 1] === "*") {
          depth++;
          i += 2;
          continue;
        }
        if (text[i] === "*" && text[i + 1] === "/") {
          depth--;
          i += 2;
          continue;
        }
        const cur = text[i];
        if (cur === "\n") line++;
        else if (cur === "\r") {
          line++;
          if (text[i + 1] === "\n") i++;
        } else {
          header += cur;
        }
        i++;
      }
      header += "\n";
      continue;
    }
    break;
  }
  return header;
}

function isGenerated(buf) {
  const prefix = firstSourceLines(buf, GENERATED_HEADER_LINES).toString("utf8");
  return GENERATED_HEADER.test(generatedCommentHeader(prefix));
}

function checkRust() {
  const errors = [];
  const files = [];
  walkTree(repoRoot, (full, name) => {
    if (name.endsWith(".rs")) files.push(path.resolve(full));
  }, SKIP_WALK, errors);
  files.sort(byDisplay);
  for (const file of files) {
    let buf;
    try {
      buf = fs.readFileSync(file);
    } catch (error) {
      errors.push(readError(file, error));
      continue;
    }
    if (isGenerated(buf)) continue;
    const lines = countSourceLines(buf);
    if (lines > MAX_HANDWRITTEN_RUST_LINES) {
      errors.push(
        `${display(file)}: ${lines} 行，超过手写 Rust 上限 ${MAX_HANDWRITTEN_RUST_LINES}`,
      );
    }
  }
  return errors;
}

function plainText(node) {
  // mdast 把 HTML 标签拆成 html 节点，可见文字留在相邻 text。不另写 HTML 解析器。
  if (node.type === "text" || node.type === "inlineCode") return node.value;
  if (node.type === "image" || node.type === "imageReference") return node.alt ?? "";
  if (!node.children) return "";
  return node.children.map(plainText).join("");
}

function headingSlugs(file, fromMarkdown, GithubSlugger, cache) {
  const key = path.resolve(file);
  if (cache.has(key)) return cache.get(key);
  const text = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "");
  const tree = fromMarkdown(text);
  const slugger = new GithubSlugger();
  const slugs = new Set();
  const visit = (node) => {
    if (node.type === "heading") {
      const slug = slugger.slug(plainText(node));
      if (slug) slugs.add(slug);
    }
    if (node.children) node.children.forEach(visit);
  };
  visit(tree);
  cache.set(key, slugs);
  return slugs;
}

function insideRepo(abs) {
  const rel = path.relative(repoRoot, abs);
  return rel === "" || (rel !== ".." && !rel.startsWith(`..${path.sep}`) && !path.isAbsolute(rel));
}

function locateInRepo(abs) {
  if (!insideRepo(abs)) return { outside: true };
  const rel = path.relative(repoRoot, abs);
  let current = repoRoot;
  if (rel !== "") {
    for (const part of rel.split(path.sep).filter(Boolean)) {
      let names;
      try {
        names = fs.readdirSync(current);
      } catch (error) {
        return { unreadable: error };
      }
      const wanted = part.normalize("NFC");
      const match = names.find((name) => name.normalize("NFC") === wanted);
      if (!match) return null;
      current = path.join(current, match);
    }
  }
  try {
    const real = fs.realpathSync(current);
    if (!insideRepo(real)) return { outside: true };
    const stat = fs.statSync(real);
    if (!stat.isFile() && !stat.isDirectory()) return null;
    return { path: real, stat };
  } catch (error) {
    if (error && (error.code === "EACCES" || error.code === "EPERM" || error.code === "EIO")) {
      return { unreadable: error };
    }
    return null;
  }
}

function decodeComponent(value) {
  try {
    return decodeURIComponent(value);
  } catch {
    return null;
  }
}

function splitLocalUrl(raw) {
  let rest = raw.trim();
  const hash = rest.indexOf("#");
  let fragment = "";
  if (hash !== -1) {
    fragment = rest.slice(hash + 1);
    rest = rest.slice(0, hash);
  }
  const query = rest.indexOf("?");
  if (query !== -1) rest = rest.slice(0, query);
  return { pathPart: rest, fragment };
}

function lineCount(file) {
  return countSourceLines(fs.readFileSync(file));
}

function lineAnchorOk(file, fragment) {
  const match = LINE_ANCHOR.exec(fragment);
  if (!match) return false;
  const start = Number(match[1]);
  const end = match[2] === undefined ? start : Number(match[2]);
  if (start < 1 || end < start) return false;
  return end <= lineCount(file);
}

function fragmentOk(target, fragment, fromMarkdown, GithubSlugger, cache) {
  const decoded = decodeComponent(fragment);
  if (decoded === null) return { ok: false };
  if (decoded === "") return { ok: true };
  if (target.stat.isDirectory()) {
    return directoryFragmentOk(target.path, decoded, fromMarkdown, GithubSlugger, cache);
  }
  const ext = path.extname(target.path).toLowerCase();
  if (ext === ".md" || ext === ".markdown") {
    const slugs = headingSlugs(target.path, fromMarkdown, GithubSlugger, cache);
    return { ok: slugs.has(decoded) };
  }
  return { ok: lineAnchorOk(target.path, decoded) };
}

function directoryFragmentOk(dir, fragment, fromMarkdown, GithubSlugger, cache) {
  const readme = path.join(dir, "README.md");
  const found = locateReadme(readme);
  if (!found) {
    return {
      ok: false,
      detail: `${display(dir)}: 目录片段需要根 README.md，但 README.md 缺失`,
    };
  }
  if (found.unreadable) return { ok: false, detail: readError(readme, found.unreadable) };
  if (found.outside) {
    return { ok: false, detail: `${display(dir)}: 目录片段的根 README.md 超出仓库` };
  }
  if (!found.stat || !found.stat.isFile()) {
    return {
      ok: false,
      detail: `${display(dir)}: 目录片段需要根 README.md，但 README.md 不是仓库内文件`,
    };
  }
  let slugs;
  try {
    slugs = headingSlugs(found.path, fromMarkdown, GithubSlugger, cache);
  } catch (error) {
    return { ok: false, detail: readError(found.path, error) };
  }
  if (!slugs.has(fragment)) {
    return { ok: false, detail: `片段 #${fragment} 在 ${display(found.path)} 中不存在` };
  }
  return { ok: true };
}

function locateReadme(readme) {
  if (!insideRepo(readme)) return { outside: true };
  try {
    const real = fs.realpathSync(readme);
    if (!insideRepo(real)) return { outside: true };
    return { path: real, stat: fs.statSync(real) };
  } catch (error) {
    if (error && (error.code === "ENOENT" || error.code === "ENOTDIR")) return null;
    return { unreadable: error };
  }
}

function resolveLocal(fromFile, rawUrl) {
  const trimmed = rawUrl.trim();
  if (trimmed === "") return { error: "空链接" };
  if (trimmed.startsWith("//") || EXTERNAL_SCHEME.test(trimmed)) return { external: true };
  if (/^[a-z]:[\\/]/i.test(trimmed)) {
    const { pathPart, fragment } = splitLocalUrl(trimmed);
    return { abs: path.resolve(pathPart), fragment, shown: trimmed };
  }
  if (/^[a-z][a-z0-9+.-]*:/i.test(trimmed)) {
    if (!/^file:/i.test(trimmed)) return { external: true };
    let parsed;
    try {
      parsed = new URL(trimmed);
    } catch {
      return { error: `无法解析 file URL ${trimmed}` };
    }
    let abs;
    try {
      abs = fileURLToPath(parsed);
    } catch {
      return { error: `无法解析 file URL ${trimmed}` };
    }
    const fragment = parsed.hash.startsWith("#") ? parsed.hash.slice(1) : "";
    return { abs: path.resolve(abs), fragment, shown: trimmed };
  }
  const { pathPart, fragment } = splitLocalUrl(trimmed);
  if (pathPart === "") return { abs: path.resolve(fromFile), fragment, shown: trimmed };
  const decoded = decodeComponent(pathPart);
  if (decoded === null) return { error: `无法解码本地链接 ${trimmed}` };
  const normalized = decoded.normalize("NFC").replace(/\\/g, "/");
  const abs = normalized.startsWith("/")
    ? path.resolve(repoRoot, normalized.slice(1))
    : path.resolve(path.dirname(fromFile), normalized);
  return { abs, fragment, shown: trimmed, decoded: normalized };
}

function checkTarget(fromFile, line, rawUrl, errors, parsers, cache) {
  const resolved = resolveLocal(fromFile, rawUrl);
  if (resolved.external) return;
  if (resolved.error) {
    errors.push(`${display(fromFile)}:${line}: ${resolved.error}`);
    return;
  }
  const found = locateInRepo(resolved.abs);
  if (!found || found.unreadable || found.outside || !found.stat) {
    if (found && found.unreadable) {
      errors.push(`${display(fromFile)}:${line}: ${readError(resolved.abs, found.unreadable)}`);
      return;
    }
    const where = (found && found.outside) || !insideRepo(resolved.abs) ? "超出仓库" : "不存在";
    const shown = resolved.decoded && resolved.decoded !== resolved.shown
      ? `${resolved.shown}（${resolved.decoded}）`
      : resolved.shown;
    errors.push(`${display(fromFile)}:${line}: 本地链接${where} ${shown}`);
    return;
  }
  let fragmentResult;
  try {
    fragmentResult = fragmentOk(
      found,
      resolved.fragment,
      parsers.fromMarkdown,
      parsers.GithubSlugger,
      cache,
    );
  } catch (error) {
    errors.push(`${display(fromFile)}:${line}: ${readError(found.path, error)}`);
    return;
  }
  if (!fragmentResult.ok) {
    const label = decodeComponent(resolved.fragment) ?? resolved.fragment;
    const detail = fragmentResult.detail ?? `片段 #${label} 在 ${display(found.path)} 中不存在`;
    errors.push(`${display(fromFile)}:${line}: ${detail}`);
  }
}

function visit(node, fn) {
  fn(node);
  if (node.children) node.children.forEach((child) => visit(child, fn));
}

function checkLinks(files, parsers) {
  const errors = [];
  const cache = new Map();
  for (const file of files) {
    let text;
    try {
      text = fs.readFileSync(file, "utf8").replace(/^\uFEFF/, "");
    } catch (error) {
      errors.push(`${display(file)}: 无法读取 (${error.message})`);
      continue;
    }
    let tree;
    try {
      tree = parsers.fromMarkdown(text);
    } catch (error) {
      errors.push(`${display(file)}: CommonMark 解析失败 (${error.message})`);
      continue;
    }
    const definitions = new Map();
    visit(tree, (node) => {
      if (node.type === "definition") definitions.set(node.identifier, node);
    });
    visit(tree, (node) => {
      const line = node.position?.start?.line ?? 1;
      if (node.type === "definition" || node.type === "link" || node.type === "image") {
        checkTarget(file, line, node.url ?? "", errors, parsers, cache);
        return;
      }
      if (node.type !== "linkReference" && node.type !== "imageReference") return;
      if (definitions.has(node.identifier)) return;
      const label = node.label || node.identifier;
      errors.push(`${display(file)}:${line}: 解析出的引用式链接没有对应定义 [${label}]`);
    });
  }
  return errors;
}

async function loadParsers() {
  try {
    const mdast = await import("mdast-util-from-markdown");
    const slugger = await import("github-slugger");
    if (typeof mdast.fromMarkdown !== "function" || typeof slugger.default !== "function") {
      throw new Error("链接解析依赖的导出不完整");
    }
    return { fromMarkdown: mdast.fromMarkdown, GithubSlugger: slugger.default };
  } catch (error) {
    if (error?.code === "ERR_MODULE_NOT_FOUND") {
      throw new Error("依赖未安装。请在仓库根目录执行 npm --prefix circus-sandbox/qa ci", {
        cause: error,
      });
    }
    throw error;
  }
}

function usage() {
  console.error("用法: node check.mjs [--format]");
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--format")) {
    usage();
    process.exit(2);
  }
  const format = args.includes("--format");
  const docErrors = [];
  const docs = markdownFiles(docErrors);
  if (docErrors.length > 0) {
    for (const error of docErrors) console.error(error);
    process.exit(1);
  }
  if (docs.length === 0) {
    console.error("没有找到白名单内的 Markdown 文件");
    process.exit(1);
  }
  if (format) {
    process.exit(await runPrettier(docs, true));
  }
  let failed = false;
  if ((await runMarkdownlint(docs)) !== 0) failed = true;
  if ((await runPrettier(docs, false)) !== 0) failed = true;
  console.log("本地链接");
  let linkErrors = [];
  try {
    const parsers = await loadParsers();
    const scopeErrors = [];
    const scoped = linkFiles(docs, scopeErrors);
    linkErrors = [...scopeErrors, ...checkLinks(scoped, parsers)];
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    failed = true;
  }
  console.log("手写 Rust 行数");
  const rustErrors = checkRust();
  for (const error of [...linkErrors, ...rustErrors]) console.error(error);
  if (linkErrors.length > 0 || rustErrors.length > 0) failed = true;
  process.exit(failed ? 1 : 0);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
